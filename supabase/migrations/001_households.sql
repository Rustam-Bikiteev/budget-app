CREATE FUNCTION budget_private.valid_settings(value jsonb) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE STRICT SET search_path = pg_catalog
AS $$ DECLARE c jsonb; ids text[]:=ARRAY[]::text[]; BEGIN
  IF jsonb_typeof(value)<>'object' OR coalesce(jsonb_typeof(value->'categories'),'null')<>'array' THEN RETURN false; END IF;
  IF jsonb_array_length(value->'categories') NOT BETWEEN 1 AND 100 THEN RETURN false; END IF;
  FOR c IN SELECT jsonb_array_elements(value->'categories') LOOP
    IF jsonb_typeof(c)<>'object' OR coalesce(jsonb_typeof(c->'id'),'null')<>'string'
      OR coalesce(jsonb_typeof(c->'name'),'null')<>'string' OR coalesce(jsonb_typeof(c->'color'),'null')<>'string'
      OR length(c->>'id') NOT BETWEEN 1 AND 100 OR length(btrim(c->>'name')) NOT BETWEEN 1 AND 100
      OR (c->>'color') !~ '^#[0-9a-fA-F]{6}$' OR (c ? 'default' AND jsonb_typeof(c->'default')<>'boolean')
      OR c->>'id'=ANY(ids) THEN RETURN false; END IF;
    ids:=array_append(ids,c->>'id');
  END LOOP;
  RETURN true;
END $$;
REVOKE ALL ON FUNCTION budget_private.valid_settings(jsonb) FROM PUBLIC, anon, authenticated;
CREATE TABLE public.households (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
  settings jsonb NOT NULL DEFAULT '{"categories":[{"id":"general","name":"Общие","color":"#8b80c9","default":true}]}'::jsonb
    CHECK (budget_private.valid_settings(settings)),
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0)
);
CREATE TABLE public.household_members (
  household_id uuid NOT NULL REFERENCES public.households(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  role text NOT NULL CHECK (role IN ('owner','member')),
  PRIMARY KEY (household_id,user_id)
);
CREATE INDEX household_members_user ON public.household_members(user_id,household_id);
CREATE TABLE public.months (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id uuid NOT NULL REFERENCES public.households(id),
  year integer NOT NULL CHECK (year BETWEEN 1900 AND 9999),
  month integer NOT NULL CHECK (month BETWEEN 1 AND 12),
  half integer NOT NULL CHECK (half IN (1,2)),
  income numeric NOT NULL DEFAULT 0 CHECK (income BETWEEN 0 AND 1000000000000 AND income = round(income,2)),
  saved numeric NOT NULL DEFAULT 0 CHECK (saved BETWEEN 0 AND 1000000000000 AND saved = round(saved,2)),
  transferred numeric CHECK (transferred BETWEEN 0 AND 1000000000000 AND transferred = round(transferred,2)),
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
  UNIQUE (household_id,year,month,half), UNIQUE (household_id,id)
);
CREATE TABLE public.entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id uuid NOT NULL REFERENCES public.households(id),
  month_id bigint NOT NULL,
  type text NOT NULL CHECK (type IN ('mandatory','planned')),
  category text NOT NULL CHECK (length(category) BETWEEN 1 AND 100),
  name text NOT NULL DEFAULT '' CHECK (length(name) <= 500),
  planned numeric NOT NULL DEFAULT 0 CHECK (planned BETWEEN 0 AND 1000000000000 AND planned = round(planned,2)),
  actual numeric NOT NULL DEFAULT 0 CHECK (actual BETWEEN 0 AND 1000000000000 AND actual = round(actual,2)),
  is_reserve boolean NOT NULL DEFAULT false CHECK (NOT is_reserve OR type = 'mandatory'),
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
  FOREIGN KEY (household_id,month_id) REFERENCES public.months(household_id,id) ON DELETE CASCADE
);
CREATE INDEX entries_period ON public.entries(household_id,month_id);
CREATE TABLE public.backlog (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id uuid NOT NULL REFERENCES public.households(id),
  category text NOT NULL CHECK (length(category) BETWEEN 1 AND 100),
  name text NOT NULL DEFAULT '' CHECK (length(name) <= 500),
  planned numeric NOT NULL DEFAULT 0 CHECK (planned BETWEEN 0 AND 1000000000000 AND planned = round(planned,2)),
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0)
);
CREATE INDEX backlog_household ON public.backlog(household_id);
CREATE TABLE budget_private.requests (
  household_id uuid NOT NULL REFERENCES public.households(id),
  user_id uuid NOT NULL REFERENCES auth.users(id),
  request_id uuid NOT NULL,
  operation text NOT NULL,
  payload jsonb NOT NULL,
  result jsonb NOT NULL,
  PRIMARY KEY (household_id,user_id,request_id)
);
CREATE TABLE budget_private.invites (
  token_hash text PRIMARY KEY,
  household_id uuid NOT NULL REFERENCES public.households(id),
  expires_at timestamptz NOT NULL,
  used_by uuid REFERENCES auth.users(id)
);

-- Definer helper avoids membership-policy recursion. Only a boolean for the
-- caller's own membership can be disclosed, never another user's membership.
CREATE FUNCTION public.budget_is_member(household_id uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public
AS $$ SELECT EXISTS (SELECT 1 FROM public.household_members m
  WHERE m.household_id = $1 AND m.user_id = auth.uid()) $$;
REVOKE ALL ON FUNCTION public.budget_is_member(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.budget_is_member(uuid) TO authenticated;

DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['households','household_members','months','entries','backlog'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC, anon, authenticated',t);
    EXECUTE format('GRANT SELECT ON public.%I TO authenticated',t);
    EXECUTE format('CREATE POLICY household_read ON public.%I FOR SELECT TO authenticated USING (public.budget_is_member(%I))',
      t, CASE WHEN t = 'households' THEN 'id' ELSE 'household_id' END);
  END LOOP;
END $$;
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['months','entries','backlog'] LOOP
    EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated',pg_get_serial_sequence('public.'||t,'id'));
  END LOOP;
END $$;

CREATE FUNCTION public.budget_create_household(name text, request_id uuid) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public
AS $$ DECLARE h public.households; old budget_private.requests; u uuid := auth.uid(); BEGIN
  IF u IS NULL THEN RAISE EXCEPTION 'not_authenticated' USING ERRCODE='42501'; END IF;
  IF request_id IS NULL THEN RAISE EXCEPTION 'request_required'; END IF;
  -- Auth user lock makes onboarding retries safe before a household exists.
  PERFORM 1 FROM auth.users WHERE id = u FOR UPDATE;
  SELECT r.* INTO old FROM budget_private.requests r
    WHERE r.user_id=u AND r.request_id=$2 AND r.operation='create_household';
  IF FOUND THEN
    IF old.payload <> jsonb_build_object('name',$1) THEN RAISE EXCEPTION 'request_mismatch'; END IF;
    IF NOT public.budget_is_member(old.household_id) THEN RAISE EXCEPTION 'not_member' USING ERRCODE='42501'; END IF;
    RETURN old.result;
  END IF;
  INSERT INTO public.households(name) VALUES ($1) RETURNING * INTO h;
  INSERT INTO public.household_members VALUES (h.id,u,'owner');
  INSERT INTO budget_private.requests VALUES (h.id,u,$2,'create_household',jsonb_build_object('name',$1),to_jsonb(h));
  RETURN to_jsonb(h);
END $$;

CREATE FUNCTION public.budget_list_households() RETURNS jsonb
LANGUAGE sql STABLE SECURITY INVOKER SET search_path = pg_catalog, public
AS $$ SELECT coalesce(jsonb_agg(to_jsonb(h) || jsonb_build_object('role',m.role) ORDER BY h.name,h.id),'[]'::jsonb)
  FROM public.households h JOIN public.household_members m ON m.household_id=h.id WHERE m.user_id=auth.uid() $$;

CREATE FUNCTION public.budget_household_details(household_id uuid) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY INVOKER SET search_path = pg_catalog, public
AS $$ DECLARE result jsonb; BEGIN
  IF NOT public.budget_is_member($1) THEN RAISE EXCEPTION 'not_member' USING ERRCODE='42501'; END IF;
  SELECT to_jsonb(h) || jsonb_build_object('members',(SELECT jsonb_agg(to_jsonb(m) ORDER BY m.user_id)
    FROM public.household_members m WHERE m.household_id=$1)) INTO result FROM public.households h WHERE h.id=$1;
  RETURN result;
END $$;

CREATE FUNCTION public.budget_create_invite(household_id uuid, request_id uuid, ttl_seconds integer DEFAULT 86400) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public
AS $$ DECLARE token text; result jsonb; old budget_private.requests; BEGIN
  PERFORM 1 FROM public.households h WHERE h.id=$1 FOR UPDATE;
  IF NOT EXISTS (SELECT 1 FROM public.household_members m WHERE m.household_id=$1 AND m.user_id=auth.uid() AND role='owner')
    THEN RAISE EXCEPTION 'owner_required' USING ERRCODE='42501'; END IF;
  IF request_id IS NULL THEN RAISE EXCEPTION 'request_required'; END IF;
  SELECT * INTO old FROM budget_private.requests r WHERE r.household_id=$1 AND r.user_id=auth.uid() AND r.request_id=$2;
  IF FOUND THEN
    IF old.operation <> 'invite' OR old.payload <> jsonb_build_object('ttl_seconds',$3) THEN RAISE EXCEPTION 'request_mismatch'; END IF;
    RETURN old.result;
  END IF;
  IF ttl_seconds IS NULL OR ttl_seconds NOT BETWEEN 60 AND 604800 THEN RAISE EXCEPTION 'invalid_ttl'; END IF;
  token := replace(gen_random_uuid()::text,'-','') || replace(gen_random_uuid()::text,'-','');
  INSERT INTO budget_private.invites VALUES (encode(sha256(convert_to(token,'UTF8')),'hex'),$1,clock_timestamp()+make_interval(secs=>$3),NULL)
    RETURNING jsonb_build_object('token',token,'expires_at',expires_at) INTO result;
  INSERT INTO budget_private.requests VALUES ($1,auth.uid(),$2,'invite',jsonb_build_object('ttl_seconds',$3),result);
  RETURN result;
END $$;

CREATE FUNCTION public.budget_join_household(token text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public
AS $$ DECLARE i budget_private.invites; u uuid:=auth.uid(); BEGIN
  IF u IS NULL THEN RAISE EXCEPTION 'not_authenticated' USING ERRCODE='42501'; END IF;
  SELECT * INTO i FROM budget_private.invites x WHERE token_hash=encode(sha256(convert_to($1,'UTF8')),'hex') FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'invalid_invite'; END IF;
  -- Same-user network retry returns success; everyone else sees a spent token.
  IF i.used_by=u THEN RETURN jsonb_build_object('household_id',i.household_id); END IF;
  IF i.used_by IS NOT NULL OR i.expires_at <= clock_timestamp() THEN RAISE EXCEPTION 'invalid_invite'; END IF;
  INSERT INTO public.household_members VALUES (i.household_id,u,'member') ON CONFLICT DO NOTHING;
  UPDATE budget_private.invites SET used_by=u WHERE token_hash=i.token_hash;
  RETURN jsonb_build_object('household_id',i.household_id);
END $$;

-- All writes use one endpoint: a household lock serializes financial validation,
-- a request UUID deduplicates transport retries, and revisions reject stale edits.
CREATE FUNCTION public.budget_mutate(household_id uuid, request_id uuid, operation text, payload jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public
AS $$
DECLARE
  u uuid:=auth.uid(); h public.households; m public.months; src public.months;
  e public.entries; r public.entries; b public.backlog; old budget_private.requests;
  p jsonb:=$4; result jsonb; amount numeric; available numeric; source text;
  mid bigint; rid bigint; expected bigint; row_json jsonb;
BEGIN
  SELECT * INTO h FROM public.households x WHERE x.id=$1 FOR UPDATE;
  IF NOT FOUND OR NOT public.budget_is_member($1) THEN RAISE EXCEPTION 'not_member' USING ERRCODE='42501'; END IF;
  IF request_id IS NULL THEN RAISE EXCEPTION 'request_required'; END IF;
  IF p IS NULL OR jsonb_typeof(p)<>'object' THEN RAISE EXCEPTION 'invalid_payload'; END IF;
  SELECT * INTO old FROM budget_private.requests x WHERE x.household_id=$1 AND x.user_id=u AND x.request_id=$2;
  IF FOUND THEN
    IF old.operation IS DISTINCT FROM $3 OR old.payload <> p THEN RAISE EXCEPTION 'request_mismatch'; END IF;
    RETURN old.result;
  END IF;
  IF p ?| ARRAY['household_id','user_id','role','revision','is_admin'] THEN RAISE EXCEPTION 'forbidden_field'; END IF;
  expected := (p->>'expected_revision')::bigint;

  IF operation='update_settings' THEN
    IF h.revision IS DISTINCT FROM expected THEN RAISE EXCEPTION 'revision_conflict' USING ERRCODE='40001'; END IF;
    IF NOT EXISTS (SELECT 1 FROM public.household_members x WHERE x.household_id=$1 AND x.user_id=u AND x.role='owner')
      THEN RAISE EXCEPTION 'owner_required' USING ERRCODE='42501'; END IF;
    UPDATE public.households x SET name=coalesce(p->>'name',x.name),settings=coalesce(p->'settings',x.settings),revision=x.revision+1
      WHERE x.id=$1 RETURNING to_jsonb(x) INTO row_json;
  ELSIF operation='create_month' THEN
    IF p->>'copy_from_id' IS NOT NULL THEN
      SELECT * INTO src FROM public.months x WHERE x.household_id=$1 AND x.id=(p->>'copy_from_id')::bigint FOR UPDATE;
      IF NOT FOUND THEN RAISE EXCEPTION 'not_found'; END IF;
      IF src.revision IS DISTINCT FROM expected THEN RAISE EXCEPTION 'revision_conflict' USING ERRCODE='40001'; END IF;
    END IF;
    INSERT INTO public.months(household_id,year,month,half) VALUES ($1,(p->>'year')::int,(p->>'month')::int,(p->>'half')::int) RETURNING * INTO m;
    IF src.id IS NOT NULL THEN
      INSERT INTO public.entries(household_id,month_id,type,category,name,planned,actual,is_reserve)
        SELECT $1,m.id,x.type,x.category,x.name,x.planned,0,x.is_reserve FROM public.entries x WHERE x.household_id=$1 AND x.month_id=src.id;
    END IF;
    row_json:=to_jsonb(m);
  ELSIF operation='delete_month' THEN
    SELECT * INTO m FROM public.months x WHERE x.household_id=$1 AND x.id=(p->>'month_id')::bigint FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'not_found'; END IF;
    IF m.revision IS DISTINCT FROM expected THEN RAISE EXCEPTION 'revision_conflict' USING ERRCODE='40001'; END IF;
    row_json:=to_jsonb(m);
    DELETE FROM public.months WHERE id=m.id;
    m:=NULL;
  ELSIF operation IN ('create_backlog','update_backlog','delete_backlog','backlog_to_entry') THEN
    IF operation<>'create_backlog' THEN
      SELECT * INTO b FROM public.backlog x WHERE x.household_id=$1 AND x.id=(p->>'id')::bigint FOR UPDATE;
      IF NOT FOUND THEN RAISE EXCEPTION 'not_found'; END IF;
      IF b.revision IS DISTINCT FROM expected THEN RAISE EXCEPTION 'revision_conflict' USING ERRCODE='40001'; END IF;
    END IF;
    IF operation='create_backlog' THEN
      INSERT INTO public.backlog(household_id,category,name,planned) VALUES ($1,p->>'category',coalesce(p->>'name',''),coalesce((p->>'planned')::numeric,0))
        RETURNING to_jsonb(backlog.*) INTO row_json;
    ELSIF operation='update_backlog' THEN
      UPDATE public.backlog x SET category=coalesce(p->>'category',x.category),name=coalesce(p->>'name',x.name),
        planned=coalesce((p->>'planned')::numeric,x.planned),revision=x.revision+1 WHERE x.id=b.id RETURNING to_jsonb(x) INTO row_json;
    ELSE
      IF operation='backlog_to_entry' THEN
        SELECT * INTO m FROM public.months x WHERE x.household_id=$1 AND x.id=(p->>'month_id')::bigint FOR UPDATE;
        IF NOT FOUND THEN RAISE EXCEPTION 'not_found'; END IF;
        IF m.revision IS DISTINCT FROM (p->>'expected_month_revision')::bigint THEN RAISE EXCEPTION 'revision_conflict' USING ERRCODE='40001'; END IF;
        INSERT INTO public.entries(household_id,month_id,type,category,name,planned) VALUES ($1,m.id,'planned',b.category,b.name,b.planned)
          RETURNING to_jsonb(entries.*) INTO row_json;
        UPDATE public.months SET revision=revision+1 WHERE id=m.id RETURNING * INTO m;
      ELSE row_json:=to_jsonb(b); END IF;
      DELETE FROM public.backlog WHERE id=b.id;
    END IF;
  ELSE
    -- Entry updates may never change month_id. Cross-month moves use explicit RPC.
    IF operation IN ('update_entry','delete_entry','entry_to_backlog') THEN
      IF p ? 'month_id' THEN RAISE EXCEPTION 'forbidden_field'; END IF;
      SELECT * INTO e FROM public.entries x WHERE x.household_id=$1 AND x.id=(p->>'id')::bigint FOR UPDATE;
      IF NOT FOUND THEN RAISE EXCEPTION 'not_found'; END IF;
      IF e.revision IS DISTINCT FROM expected THEN RAISE EXCEPTION 'revision_conflict' USING ERRCODE='40001'; END IF;
      mid:=e.month_id;
    ELSE mid:=(p->>'month_id')::bigint; END IF;
    SELECT * INTO m FROM public.months x WHERE x.household_id=$1 AND x.id=mid FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'not_found'; END IF;
    IF operation NOT IN ('update_entry','delete_entry','entry_to_backlog') AND m.revision IS DISTINCT FROM expected
      THEN RAISE EXCEPTION 'revision_conflict' USING ERRCODE='40001'; END IF;
    IF operation='update_month' THEN
      UPDATE public.months x SET income=coalesce((p->>'income')::numeric,x.income),saved=coalesce((p->>'saved')::numeric,x.saved),
        transferred=CASE WHEN p ? 'transferred' THEN (p->>'transferred')::numeric ELSE x.transferred END WHERE x.id=m.id;
    ELSIF operation='create_entry' THEN
      INSERT INTO public.entries(household_id,month_id,type,category,name,planned,actual,is_reserve)
        VALUES ($1,m.id,p->>'type',p->>'category',coalesce(p->>'name',''),coalesce((p->>'planned')::numeric,0),coalesce((p->>'actual')::numeric,0),coalesce((p->>'is_reserve')::boolean,false))
        RETURNING to_jsonb(entries.*) INTO row_json;
    ELSIF operation='update_entry' THEN
      UPDATE public.entries x SET type=coalesce(p->>'type',x.type),category=coalesce(p->>'category',x.category),name=coalesce(p->>'name',x.name),
        planned=coalesce((p->>'planned')::numeric,x.planned),actual=coalesce((p->>'actual')::numeric,x.actual),
        is_reserve=coalesce((p->>'is_reserve')::boolean,x.is_reserve),revision=x.revision+1 WHERE x.id=e.id RETURNING to_jsonb(x) INTO row_json;
    ELSIF operation IN ('delete_entry','entry_to_backlog') THEN
      IF operation='entry_to_backlog' THEN
        INSERT INTO public.backlog(household_id,category,name,planned) VALUES ($1,e.category,e.name,e.planned) RETURNING to_jsonb(backlog.*) INTO row_json;
      ELSE row_json:=to_jsonb(e); END IF;
      DELETE FROM public.entries WHERE id=e.id;
    ELSIF operation IN ('quick_expense','cover_overrun') THEN
      source:=p->>'source';
      IF source IS NULL OR source NOT IN ('free','saved','reserve') OR (operation='cover_overrun' AND source='free') THEN RAISE EXCEPTION 'invalid_source'; END IF;
      IF operation='cover_overrun' OR p->>'id' IS NOT NULL THEN
        SELECT * INTO e FROM public.entries x WHERE x.household_id=$1 AND x.month_id=m.id AND x.id=(p->>'id')::bigint AND x.type='planned' FOR UPDATE;
        IF NOT FOUND THEN RAISE EXCEPTION 'not_found'; END IF;
      ELSE
        -- Resolve the same planned row as saveQuick, inside the household lock.
        SELECT * INTO e FROM public.entries x WHERE x.household_id=$1 AND x.month_id=m.id
          AND x.type='planned' AND x.category=p->>'category'
          AND lower(btrim(x.name))=lower(btrim(coalesce(p->>'name','Без названия')))
          ORDER BY x.id LIMIT 1 FOR UPDATE;
      END IF;
      IF operation='cover_overrun' THEN amount:=greatest(e.actual-e.planned,0);
      ELSE amount:=(p->>'amount')::numeric; END IF;
      IF amount IS NULL OR NOT (amount>0 AND amount<=1000000000000 AND amount=round(amount,2)) THEN RAISE EXCEPTION 'invalid_amount'; END IF;
      IF source='saved' THEN available:=m.saved;
      ELSIF source='reserve' THEN
        SELECT * INTO r FROM public.entries x WHERE x.household_id=$1 AND x.month_id=m.id AND x.type='mandatory' AND x.is_reserve
          ORDER BY x.id LIMIT 1 FOR UPDATE;
        available:=coalesce(greatest(r.planned-r.actual,0),0);
      END IF;
      IF source<>'free' THEN
        IF operation='cover_overrun' THEN amount:=least(amount,available); END IF;
        IF amount<=0 OR amount>available THEN RAISE EXCEPTION 'insufficient_funds'; END IF;
        IF source='saved' THEN UPDATE public.months SET saved=saved-amount WHERE id=m.id;
        ELSE UPDATE public.entries SET actual=actual+amount,revision=revision+1 WHERE id=r.id; END IF;
      END IF;
      IF operation='cover_overrun' THEN
        UPDATE public.entries SET planned=planned+amount,revision=revision+1 WHERE id=e.id RETURNING to_jsonb(entries.*) INTO row_json;
      ELSIF e.id IS NOT NULL THEN
        UPDATE public.entries SET planned=greatest(planned,actual)+amount,actual=actual+amount,revision=revision+1 WHERE id=e.id RETURNING to_jsonb(entries.*) INTO row_json;
      ELSE
        INSERT INTO public.entries(household_id,month_id,type,category,name,planned,actual)
          VALUES ($1,m.id,'planned',p->>'category',coalesce(p->>'name','Без названия'),amount,amount) RETURNING to_jsonb(entries.*) INTO row_json;
      END IF;
    ELSE RAISE EXCEPTION 'unknown_operation'; END IF;
    UPDATE public.months SET revision=revision+1 WHERE id=m.id RETURNING * INTO m;
    IF operation='update_month' THEN row_json:=to_jsonb(m); END IF;
  END IF;
  result:=jsonb_build_object('row',row_json,'month',CASE WHEN m.id IS NULL THEN NULL ELSE to_jsonb(m) END);
  INSERT INTO budget_private.requests VALUES ($1,u,$2,$3,p,result);
  RETURN result;
END $$;

